import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
let source;
try{source=await readFile('../scripts/transfer_file.py','utf8');}
catch(error){if(error.code!=='ENOENT')throw error;source=await readFile('transfer_file.py','utf8');}
const sha256=createHash('sha256').update(source).digest('hex');
await writeFile('src/transfer_client.ts','// Generated by build-transfer-client.mjs from the shipped executor helper.\n'+
  'export const transferClientSha256='+JSON.stringify(sha256)+';\n'+
  'export const transferClientSource='+JSON.stringify(source)+';\n');
